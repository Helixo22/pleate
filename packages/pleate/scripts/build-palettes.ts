// Generates src/styles/palettes.css from the seeds in src/theme/presets.ts (run: npm run palettes).
// Prints each palette's contrast ratios so a seed that fails AA is visible at a glance.
import { writeFileSync } from "node:fs";
import { contrast } from "../src/theme/color.ts";
import { createPalette, paletteToCss } from "../src/theme/palette.ts";
import { DEFAULT_PALETTE, PALETTES } from "../src/theme/presets.ts";

const out = new URL("../src/styles/palettes.css", import.meta.url);
let css = `/* Generated by scripts/build-palettes.ts from src/theme/presets.ts (do not edit by hand). */\n\n`;

for (const [name, { seed }] of Object.entries(PALETTES)) {
  const palette = createPalette(seed);
  css += `/* ${name} (${seed}) */\n${paletteToCss(`[data-palette="${name}"]`, palette, { includeRoot: name === DEFAULT_PALETTE })}\n`;
  const r = (a: string, b: string) => contrast(a, b).toFixed(2);
  console.log(
    name.padEnd(11),
    `light fill ${palette.light.accent} on ${r(palette.light.accent, palette.light.onAccent)}`,
    `ink ${palette.light.accentInk} ${r(palette.light.accentInk, "#f2f2f7")}`,
    `| dark fill ${palette.dark.accent} on ${r(palette.dark.accent, palette.dark.onAccent)}`,
    `ink ${palette.dark.accentInk} ${r(palette.dark.accentInk, "#2c2c2e")}`,
  );
}

writeFileSync(out, css);
console.log(`\nwrote ${out.pathname}`);
