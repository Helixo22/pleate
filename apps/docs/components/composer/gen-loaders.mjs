// Writes loaders.ts: one lazy import per demo file (demos/<slug>/<id>.tsx) and, for the Backgrounds set, one per
// effect component, so /composer loads only what is on the canvas. Run after adding demos:
//   node apps/docs/components/composer/gen-loaders.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const docs = new URL("../../", import.meta.url).pathname;
const demosDir = join(docs, "demos");

export function demoKeys() {
  return readdirSync(demosDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== "bits")
    .flatMap((d) =>
      readdirSync(join(demosDir, d.name))
        .filter((f) => f.endsWith(".tsx"))
        .map((f) => `${d.name}/${f.slice(0, -4)}`),
    )
    .sort();
}

// Background effects fill their parent, so the composer can use them behind a section.
export function backgrounds() {
  const out = [];
  for (const file of ["backgrounds-a.ts", "backgrounds-b.ts", "backgrounds-c.ts", "ascii.ts"]) {
    const text = readFileSync(join(demosDir, "bits", file), "utf8");
    for (const chunk of text.split(/\n  "?([a-z0-9-]+)"?: \{\n/).slice(1).reduce((acc, v, i, a) => (i % 2 ? acc : [...acc, [v, a[i + 1]]]), [])) {
      const [slug, body] = chunk;
      const name = /importName: "([A-Za-z0-9]+)/.exec(body)?.[1];
      const path = /importPath: "(pleate\/[a-z0-9/-]+)"/.exec(body)?.[1];
      if (name && path) out.push({ slug, name, path });
    }
  }
  return out.sort((a, b) => a.slug.localeCompare(b.slug));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const lines = [
    "// Generated by gen-loaders.mjs: do not edit by hand.",
    'import type { ComponentType } from "react";',
    "",
    "export const DEMO_LOADERS: Record<string, () => Promise<{ default: ComponentType }>> = {",
    ...demoKeys().map((k) => `  "${k}": () => import("@/demos/${k}"),`),
    "};",
    "",
    "// eslint-disable-next-line @typescript-eslint/no-explicit-any",
    "export const BACKGROUND_LOADERS: Record<string, () => Promise<ComponentType<any>>> = {",
    ...backgrounds().map((b) => `  "${b.slug}": () => import("${b.path}").then((m) => m.${b.name}),`),
    "};",
    "",
  ];
  writeFileSync(new URL("./loaders.ts", import.meta.url), lines.join("\n"));
  console.log("loaders.ts written");
}
